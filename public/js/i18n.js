  function detect() {
    // The URL prefix is authoritative. An un-prefixed URL renders English
    // (non-English preferences were already redirected above).
    return urlLang() || 'en';
  }

  const I18N = {
    supported: SUPPORTED,
    names: NAMES,
    lang: detect(),
    // Translate a key. Lookup order: overlay languages (window.I18N_OVERLAY —
    // tr/ko, flat), then the static DICT, then the flat app.* FLAT dict, then
    // English, then the key itself. {var} interpolation.
    t(key, vars) {
      let s;
      const ov = (typeof window !== 'undefined' && window.I18N_OVERLAY) ? window.I18N_OVERLAY[this.lang] : null;
      if (ov && ov[key] != null) {
        s = ov[key];
      } else {
        const d = DICT[this.lang] || DICT.en;
        if (d[key] != null) s = d[key];
        else if (FLAT[key]) s = FLAT[key][this.lang] != null ? FLAT[key][this.lang] : (FLAT[key].en != null ? FLAT[key].en : key);
        else s = DICT.en[key] != null ? DICT.en[key] : key;
      }
      if (vars) for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
      return s;
    },
    // Fill all data-i18n* elements in `root`.
    apply(root) {
      root = root || document;
      root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = this.t(el.getAttribute('data-i18n')); });
      root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', this.t(el.getAttribute('data-i18n-ph'))); });
      root.querySelectorAll('[data-i18n-html]').forEach((el) => { el.innerHTML = this.t(el.getAttribute('data-i18n-html')); });
      document.documentElement.lang = this.lang;
    },
    // Populate + wire any <select class="lang-switch"> found in the page.
    wireSwitchers() {
      document.querySelectorAll('select.lang-switch').forEach((sel) => {
        sel.innerHTML = VISIBLE.map((l) => `<option value="${l}"${l === this.lang ? ' selected' : ''}>${NAMES[l]}</option>`).join('');
        sel.onchange = () => this.set(sel.value);
      });
    },
    set(lang) {
      if (!SUPPORTED.includes(lang) || lang === this.lang) return;
      try { localStorage.setItem('glowbook_lang', lang); } catch (_) {}
      // Navigate to the language-prefixed URL (en = no prefix). A full load
      // re-renders every t() call in the new language and keeps the URL canonical.
      const bp = basePath();
      let target = (lang === 'en' ? '' : '/' + lang) + bp;
      if (target === '') target = '/';
      location.href = target + location.search + location.hash;
    },
    urlLang, basePath,
    // Inject <link rel="alternate" hreflang> for every language + x-default, and
    // point canonical at the current language URL. Called on load.
    injectHreflang() {
      const bp = basePath();
      const url = (l) => location.origin + (l === 'en' ? '' : '/' + l) + (bp === '/' && l !== 'en' ? '/' : bp);
      document.querySelectorAll('link[data-i18n-alt]').forEach((n) => n.remove());
      const add = (hreflang, href) => {
        const l = document.createElement('link');
        l.rel = 'alternate'; l.hreflang = hreflang; l.href = href; l.setAttribute('data-i18n-alt', '');
        document.head.appendChild(l);
      };
      VISIBLE.forEach((l) => add(l, url(l)));
      add('x-default', url('en'));
      const can = document.querySelector('link[rel="canonical"]');
      if (can) can.href = url(this.lang);
    },
  };

  window.I18N = I18N;
  window.t = (k, v) => I18N.t(k, v);

  document.addEventListener('DOMContentLoaded', () => { I18N.apply(document); I18N.wireSwitchers(); I18N.injectHreflang(); });

  // Keep the language prefix across internal <a> navigations (e.g. salon cards,
  // footer links). Only rewrites same-origin, non-file, un-prefixed paths.
  document.addEventListener('click', (e) => {
    if (I18N.lang === 'en' || e.defaultPrevented || e.button !== 0 || e.metaKey || e.ctrlKey || e.shiftKey) return;
    const a = e.target.closest && e.target.closest('a');
    if (!a || a.target === '_blank') return;
    const href = a.getAttribute('href');
    if (!href || href[0] !== '/' || href[1] === '/') return;   // internal absolute only
    if (LANG_RE.test(href)) return;                            // already prefixed
    if (/\.[a-z0-9]+(\?|$)/i.test(href)) return;               // static file
    e.preventDefault();
    location.href = '/' + I18N.lang + href;
  });
